/* ============================================================
   PRODUCT HELPERS
   ============================================================ */

function getProductById(id) {
  return PRODUCTS.find((product) => product.id === id);
}

function getRelatedProducts(material, excludeId, count = 3) {
  return PRODUCTS
    .filter(
      (product) =>
        product.material === material &&
        product.id !== excludeId
    )
    .slice(0, count);
}

function getProductsByCategory(category) {
  return PRODUCTS.filter((product) => product.category === category);
}

function getProductsBySubcategory(category, subcategory) {
  return PRODUCTS.filter(
    (product) =>
      product.category === category &&
      product.subcategory === subcategory
  );
}

function getProductDescription(product) {
  if (!product) return "";

  if (
    product.category === "PETG" &&
    product.subcategory &&
    CATEGORY_CONFIG.PETG.subcategories[product.subcategory]
  ) {
    return CATEGORY_CONFIG.PETG.subcategories[product.subcategory].description;
  }

  return CATEGORY_CONFIG[product.category]?.description || "";
}
